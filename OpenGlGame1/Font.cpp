std::vector<uint8_t> Font::buildTexture() {
	std::vector<uint8_t> pixels(static_cast<size_t>(textureWidth) * textureHeight, 0);

	auto cellOrigin = [](int code, int& x, int& y) {
		int cell = code - firstChar;
		x = (cell % columns) * cellSize;
		y = (cell / columns) * cellSize;
	};

	for (const Glyph& glyph : glyphs) {
		int originX, originY;
		cellOrigin(static_cast<unsigned char>(glyph.character), originX, originY);
		for (int row = 0; row < glyphHeight; row++) {
			for (int col = 0; col < glyphWidth; col++) {
				if (glyph.rows[row][col] == '#') setPixel(pixels, originX + col, originY + row);
			}
		}
	}

	// Solid cell for drawing rectangles with the same shader as text
	int whiteX, whiteY;
	cellOrigin(whiteCell, whiteX, whiteY);
	for (int y = 0; y < cellSize; y++) {
		for (int x = 0; x < cellSize; x++) setPixel(pixels, whiteX + x, whiteY + y);
	}
	return pixels;
}

int Font::cellFor(char c) {
	char upper = static_cast<char>(std::toupper(static_cast<unsigned char>(c)));
	if (!hasGlyph(upper)) upper = '?';
	return static_cast<unsigned char>(upper);
}
