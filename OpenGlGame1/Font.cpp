	void setPixel(std::vector<uint8_t>& pixels, int x, int y) {
		pixels[static_cast<size_t>(y) * Font::textureWidth + x] = 255;
	}

	bool hasGlyph(char c) {
		for (const Glyph& glyph : glyphs) {
			if (glyph.character == c) return true;
		}
		return false;
	}
